"""Rewrite the direct-links block in DEMO_SCRIPT.md with current record IDs.

  python3 scripts/links.py

seed.py runs this automatically, because reseeding gives the demo records new IDs.
"""
import json
import os
import re
import subprocess

ORG = os.environ.get("SF_ORG", "trailsignup-429cdf")
BASE = "https://trailsignup-429cdfd78ec835.lightning.force.com"
SITE = "https://rhauser15.github.io/PeerCert"
APP_ID = "06mg800000AlQvwAAF"  # Sales for Tech (Tech_Sales_App)
SCRIPT = os.path.join(os.path.dirname(__file__), "..", "DEMO_SCRIPT.md")
START, END = "<!-- links:start -->", "<!-- links:end -->"


def first_id(soql, tooling=False):
    args = ["sf", "data", "query", "-o", ORG, "-q", soql, "--json"] + (["--use-tooling-api"] if tooling else [])
    out = json.loads(subprocess.run(args, capture_output=True, text=True).stdout or "{}")
    recs = out.get("result", {}).get("records", [])
    return recs[0] if recs else None


def rec_link(label, obj, soql):
    r = first_id(soql)
    return f"[{label}]({BASE}/lightning/r/{obj}/{r['Id']}/view)" if r else f"{label} (not found; run seed.py)"


def build():
    flow = first_id("SELECT ActiveVersionId FROM FlowDefinition WHERE DeveloperName = "
                    "'Yelp_Multi_Location_Lead_Routing'", tooling=True)
    flow_link = (f"[Routing Flow in Flow Builder]({BASE}/builder_platform_interaction/flowBuilder.app?flowId="
                 f"{flow['ActiveVersionId']})" if flow else "Routing Flow (not found)")
    lv = lambda label, obj, name: f"[{label}]({BASE}/lightning/o/{obj}/list?filterName={name})"
    rows = [
        ("Mockups", [
            f"[Launcher]({SITE}/)",
            f"[Piper]({SITE}/piper.html?frame=1)",
            f"[Hunter]({SITE}/hunter.html?frame=1)",
        ]),
        ("Start here", [
            f"[Open the Sales for Tech app]({BASE}/lightning/app/{APP_ID}) (click first; the links below then open inside it)",
        ]),
        ("Section 2 · Piper write-back", [
            rec_link("Sam Whitaker lead", "Lead", "SELECT Id FROM Lead WHERE Agent_Source__c = 'Piper' LIMIT 1"),
            flow_link,
            lv("Piper - Multi-Location Leads", "Lead", "Piper_Multi_Location_Leads"),
        ]),
        ("Section 4 · Leadership", [
            rec_link("Leadership dashboard", "Dashboard",
                     "SELECT Id FROM Dashboard WHERE DeveloperName = 'Find_and_Win_Leadership' LIMIT 1"),
            rec_link("Pikes Peak Food Co. (#1 operator)", "Account",
                     "SELECT Id FROM Account WHERE Hunter_Rank__c = 1 LIMIT 1"),
            rec_link("Pikes Peak opportunity", "Opportunity",
                     "SELECT Id FROM Opportunity WHERE Account.Hunter_Rank__c = 1 LIMIT 1"),
            lv("Hunter - Colorado Operators (Ranked)", "Account", "Hunter_Colorado_Operators"),
            lv("Hunter - Dark Locations (In Sequence)", "Account", "Hunter_Dark_Locations"),
            rec_link("Dark location outreach campaign", "Campaign",
                     "SELECT Id FROM Campaign WHERE Name = 'Hunter - Colorado Dark Location Outreach' LIMIT 1"),
        ]),
    ]
    lines = [START, "", "*Auto-generated by `scripts/links.py` (runs after every `seed.py`). Sign in as Rob first.*", ""]
    for title, links in rows:
        lines.append(f"**{title}**")
        lines += [f"- {l}" for l in links]
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main():
    text = open(SCRIPT).read()
    block = build()
    if START in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.replace("## Before the demo", "## Direct links\n\n" + block + "\n\n---\n\n## Before the demo", 1)
    open(SCRIPT, "w").write(text)
    print("Updated links in DEMO_SCRIPT.md")


if __name__ == "__main__":
    main()
